// Turns resolved tokens into the files Saral ships: theme CSS and a JS module
// per theme. primitive.* tokens are private to
// their theme and never written.
import { parseColor, toHex } from './color.mjs';
import { EXT } from './checks.mjs';
import { TokenError } from './errors.mjs';

const dash = (p) => p.replaceAll('.', '-');
const isPublic = (p) => !p.startsWith('primitive.');
const GENERIC = new Set(['serif', 'sans-serif', 'monospace', 'system-ui', 'ui-sans-serif', 'ui-serif', 'ui-monospace']);
// Units are always kept, even on 0: a unitless 0 is not a valid time, and
// breaks calc() for lengths.
const dim = (d) => `${d.value}${d.unit}`;

export const cssName = (path) => `--saral-${dash(path)}`;

export function cssValue(t) {
  const ext = t.extensions?.[EXT] ?? {};
  const v = t.value;
  switch (t.type) {
    case 'color':
      return toHex(parseColor(v));
    case 'dimension':
      return ext.fluid ? `clamp(${dim(ext.fluid.min)}, ${ext.fluid.preferred}, ${dim(ext.fluid.max)})` : dim(v);
    case 'duration':
      return dim(v);
    case 'cubicBezier':
      return `cubic-bezier(${v.join(', ')})`;
    case 'fontFamily':
      return [v].flat().map((f) => (GENERIC.has(f) ? f : `"${f}"`)).join(', ');
    case 'fontWeight':
      return String(v);
    case 'number':
      return `${v}${ext.cssUnit ?? ''}`;
    default:
      throw new TokenError(`type ${t.type} is not supported`);
  }
}

const LAYERS = '@layer saral.reset, saral.tokens, saral.components, saral.utilities;';
const decls = (entries, indent) => entries.map(([p, value]) => `${indent}${cssName(p)}: ${value};`).join('\n');

// Colours that differ by mode are written as light-dark(), which follows the
// inherited color-scheme. So a mode forced on any ancestor (the page, a
// section) reaches every themed element inside it. Only colours may differ
// between modes, because light-dark() only takes colours.
export function toCss(name, modes) {
  const values = [];
  for (const [p, t] of modes.light) {
    if (!isPublic(p)) continue;
    const l = cssValue(t);
    const d = modes.dark?.get(p);
    const dv = d ? cssValue(d) : l;
    if (dv === l) values.push([p, l]);
    else if (t.type === 'color') values.push([p, `light-dark(${l}, ${dv})`]);
    else throw new TokenError(`${p} differs between light and dark; only colours may`);
  }
  const reduced = [...modes.light]
    .filter(([p, t]) => isPublic(p) && t.extensions?.[EXT]?.reduced)
    .map(([p, t]) => [p, cssValue({ type: t.type, value: t.extensions[EXT].reduced, extensions: {} })]);
  const scope = `:where(:root:not([data-saral-theme]), [data-saral-theme="${name}"])`;
  const out = [
    `/* Generated by Saral from tokens/themes/${name}. Do not edit. */`,
    LAYERS,
    '@layer saral.tokens {',
    '  :where(:root:not([data-saral-theme])) {',
    '    color-scheme: light dark;',
    '  }',
    '  :where([data-saral-mode="dark"]) {',
    '    color-scheme: dark;',
    '  }',
    '  :where([data-saral-mode="light"]) {',
    '    color-scheme: light;',
    '  }',
    `  ${scope} {`,
    decls(values, '    '),
    '  }',
  ];
  if (reduced.length) out.push('  @media (prefers-reduced-motion: reduce) {', `    ${scope} {`, decls(reduced, '      '), '    }', '  }');
  out.push('}', '');
  return out.join('\n');
}

export function toJs(name, modes) {
  const obj = {};
  for (const [mode, tokens] of Object.entries(modes)) {
    obj[mode] = {};
    for (const [p, t] of tokens) if (isPublic(p)) obj[mode][p] = cssValue(t);
  }
  return `// Generated by Saral from tokens/themes/${name}. Do not edit.\nexport default ${JSON.stringify(obj, null, 2)};\n`;
}
