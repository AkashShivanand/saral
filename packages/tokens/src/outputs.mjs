// Turns resolved tokens into the files Saral ships: theme CSS, a JS module
// per theme, and one Tailwind v4 theme map. primitive.* tokens are private to
// their theme and never written.
import { parseColor, toHex } from './color.mjs';
import { EXT } from './checks.mjs';
import { TokenError } from './errors.mjs';

const dash = (p) => p.replaceAll('.', '-');
const isPublic = (p) => !p.startsWith('primitive.');
const GENERIC = new Set(['serif', 'sans-serif', 'monospace', 'system-ui', 'ui-sans-serif', 'ui-serif', 'ui-monospace']);
const dim = (d) => (d.value === 0 ? '0' : `${d.value}${d.unit}`);

export const cssName = (path) => `--saral-${dash(path)}`;

export function cssValue(t) {
  const ext = t.extensions?.[EXT] ?? {};
  const v = t.value;
  switch (t.type) {
    case 'color':
      return toHex(parseColor(v));
    case 'dimension':
      return ext.fluid ? `clamp(${dim(ext.fluid.min)}, ${ext.fluid.preferred}, ${dim(ext.fluid.max)})` : dim(v);
    case 'duration':
      return dim(v);
    case 'cubicBezier':
      return `cubic-bezier(${v.join(', ')})`;
    case 'fontFamily':
      return [v].flat().map((f) => (GENERIC.has(f) ? f : `"${f}"`)).join(', ');
    case 'fontWeight':
      return String(v);
    case 'number':
      return `${v}${ext.cssUnit ?? ''}`;
    default:
      throw new TokenError(`type ${t.type} is not supported`);
  }
}

const LAYERS = '@layer saral.reset, saral.tokens, saral.components, saral.utilities;';
const decls = (entries, indent) => entries.map(([p, t]) => `${indent}${cssName(p)}: ${cssValue(t)};`).join('\n');

export function toCss(name, modes) {
  const light = [...modes.light].filter(([p]) => isPublic(p));
  const changed = [];
  for (const [p, t] of modes.dark ?? []) {
    if (!isPublic(p)) continue;
    const l = modes.light.get(p);
    if (!l || cssValue(l) !== cssValue(t)) changed.push([p, t]);
  }
  const reduced = light
    .filter(([, t]) => t.extensions?.[EXT]?.reduced)
    .map(([p, t]) => [p, { type: t.type, value: t.extensions[EXT].reduced, extensions: {} }]);
  const own = `[data-saral-theme="${name}"]`;
  const root = ':root:not([data-saral-theme])';
  const out = [
    `/* Generated by Saral from tokens/themes/${name}. Do not edit. */`,
    LAYERS,
    '@layer saral.tokens {',
    `  :where(${root}, ${own}) {`,
    '    color-scheme: light;',
    decls(light, '    '),
    '  }',
  ];
  if (changed.length) {
    out.push(
      '  @media (prefers-color-scheme: dark) {',
      `    :where(${root}:not([data-saral-mode="light"]), ${own}:not([data-saral-mode="light"])) {`,
      '      color-scheme: dark;',
      decls(changed, '      '),
      '    }',
      '  }',
      `  :where(:root[data-saral-mode="dark"]:not([data-saral-theme]), ${own}[data-saral-mode="dark"]) {`,
      '    color-scheme: dark;',
      decls(changed, '    '),
      '  }',
    );
  }
  if (reduced.length) {
    out.push('  @media (prefers-reduced-motion: reduce) {', `    :where(${root}, ${own}) {`, decls(reduced, '      '), '    }', '  }');
  }
  out.push('}', '');
  return out.join('\n');
}

export function toJs(name, modes) {
  const obj = {};
  for (const [mode, tokens] of Object.entries(modes)) {
    obj[mode] = {};
    for (const [p, t] of tokens) if (isPublic(p)) obj[mode][p] = cssValue(t);
  }
  return `// Generated by Saral from tokens/themes/${name}. Do not edit.\nexport default ${JSON.stringify(obj, null, 2)};\n`;
}

function twName(p, t) {
  if (t.type === 'color') return `--color-${dash(p)}`;
  if (p.startsWith('radius.')) return `--radius-${dash(p.slice(7))}`;
  if (p.startsWith('font.family.')) return `--font-${dash(p.slice(12))}`;
  if (p.startsWith('font.size.')) return `--text-${dash(p.slice(10))}`;
  if (p.startsWith('space.')) return `--spacing-${dash(p.slice(6))}`;
  if (t.type === 'cubicBezier') return `--ease-${p.split('.').at(-1)}`;
  return null;
}

export function toTailwind(tokens) {
  const lines = [];
  for (const [p, t] of tokens) {
    const tw = isPublic(p) && twName(p, t);
    if (tw) lines.push(`  ${tw}: var(${cssName(p)});`);
  }
  return ['/* Generated by Saral. Do not edit. Load after a Saral theme. */', '@theme inline {', ...lines, '}', ''].join('\n');
}
