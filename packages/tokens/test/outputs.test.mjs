import { test } from 'node:test';
import assert from 'node:assert/strict';
import { cssName, cssValue, toCss, toJs, toTailwind } from '../src/outputs.mjs';
import { EXT } from '../src/checks.mjs';

const tok = (type, value, extensions = {}) => ({ type, value, extensions });
const color = (hex) => tok('color', { colorSpace: 'srgb', hex });

test('cssName prefixes and dashes the path', () => {
  assert.equal(cssName('surface.ground'), '--saral-surface-ground');
});

test('cssValue writes each token type', () => {
  assert.equal(cssValue(color('#B3491B')), '#b3491b');
  assert.equal(cssValue(tok('dimension', { value: 16, unit: 'px' })), '16px');
  assert.equal(cssValue(tok('dimension', { value: 0, unit: 'px' })), '0');
  assert.equal(cssValue(tok('duration', { value: 160, unit: 'ms' })), '160ms');
  assert.equal(cssValue(tok('cubicBezier', [0.22, 1, 0.36, 1])), 'cubic-bezier(0.22, 1, 0.36, 1)');
  assert.equal(cssValue(tok('fontFamily', ['Anek Latin', 'ui-sans-serif', 'sans-serif'])), '"Anek Latin", ui-sans-serif, sans-serif');
  assert.equal(cssValue(tok('fontWeight', 700)), '700');
  assert.equal(cssValue(tok('number', 1.5)), '1.5');
  assert.equal(cssValue(tok('number', 80, { [EXT]: { cssUnit: '%' } })), '80%');
  const fluid = { min: { value: 32, unit: 'px' }, max: { value: 56, unit: 'px' }, preferred: '1.5rem + 2.5vw' };
  assert.equal(cssValue(tok('dimension', { value: 32, unit: 'px' }, { [EXT]: { fluid } })), 'clamp(32px, 1.5rem + 2.5vw, 56px)');
  assert.throws(() => cssValue(tok('shadow', {})), /type shadow is not supported/);
});

const light = new Map([
  ['surface.ground', color('#f3f3f0')],
  ['text.default', color('#121314')],
  ['primitive.paper', color('#f3f3f0')],
  ['motion.duration.fast', tok('duration', { value: 160, unit: 'ms' }, { [EXT]: { reduced: { value: 0, unit: 'ms' } } })],
]);
const dark = new Map([...light, ['surface.ground', color('#111214')]]);
const css = toCss('ember', { light, dark });

test('toCss declares the layer order and scopes the theme to :root or its own container', () => {
  assert.ok(css.startsWith('/* Generated by Saral'));
  assert.ok(css.includes('@layer saral.reset, saral.tokens, saral.components, saral.utilities;'));
  assert.ok(css.includes(':where(:root:not([data-saral-theme]), [data-saral-theme="ember"]) {'));
  assert.ok(css.includes('--saral-surface-ground: #f3f3f0;'));
  assert.ok(!css.includes('primitive'));
});

test('toCss writes only changed tokens for dark, and honours a forced light mode', () => {
  const media = css.slice(css.indexOf('@media (prefers-color-scheme: dark)'));
  const darkBlock = media.slice(0, media.indexOf('@media (prefers-reduced-motion'));
  assert.ok(darkBlock.includes('[data-saral-theme="ember"]:not([data-saral-mode="light"])'));
  assert.ok(darkBlock.includes('--saral-surface-ground: #111214;'));
  assert.ok(!darkBlock.includes('--saral-text-default'));
  assert.ok(css.includes('[data-saral-theme="ember"][data-saral-mode="dark"]'));
});

test('toCss drops durations to their reduced value under reduced motion', () => {
  const reduced = css.slice(css.indexOf('@media (prefers-reduced-motion: reduce)'));
  assert.ok(reduced.includes('--saral-motion-duration-fast: 0;'));
});

test('toJs exports each mode as path to CSS value', async () => {
  const mod = await import('data:text/javascript,' + encodeURIComponent(toJs('ember', { light, dark })));
  assert.equal(mod.default.light['surface.ground'], '#f3f3f0');
  assert.equal(mod.default.dark['surface.ground'], '#111214');
  assert.equal(mod.default.light['primitive.paper'], undefined);
});

test('toTailwind maps Saral variables into Tailwind theme names', () => {
  const tw = toTailwind(
    new Map([
      ['surface.ground', color('#f3f3f0')],
      ['radius.box', tok('dimension', { value: 6, unit: 'px' })],
      ['font.family.sans', tok('fontFamily', ['Anek Latin'])],
      ['font.size.body', tok('dimension', { value: 16, unit: 'px' })],
      ['space.4', tok('dimension', { value: 16, unit: 'px' })],
      ['motion.ease.standard', tok('cubicBezier', [0.22, 1, 0.36, 1])],
    ]),
  );
  assert.ok(tw.includes('@theme inline {'));
  for (const line of [
    '--color-surface-ground: var(--saral-surface-ground);',
    '--radius-box: var(--saral-radius-box);',
    '--font-sans: var(--saral-font-family-sans);',
    '--text-body: var(--saral-font-size-body);',
    '--spacing-4: var(--saral-space-4);',
    '--ease-standard: var(--saral-motion-ease-standard);',
  ]) assert.ok(tw.includes(line), line);
});
